"""Write evals/<model>/report.md (confidence per run) and evals/SCORECARD.md (all models).

Usage (from the repo root): python -m evals.report
"""
import json
import statistics as st
from pathlib import Path

from evals.harness import FIELDS, is_valid_aba, norm

EVALS = Path(__file__).parent
SHORT = {"beneficiary_name": "BenName", "beneficiary_address": "BenAddr", "bank_name": "Bank",
         "bank_address": "BankAddr", "routing_number_aba": "ABA", "account_number": "Acct"}


def runs_table(data: dict) -> str:
    lines = ["| Doc | Run | " + " | ".join(SHORT[f] for f in FIELDS) + " | Sec |",
             "|---|---|" + "---|" * (len(FIELDS) + 1)]
    for r in data["results"]:
        if "error" in r:
            lines.append(f"| {r['doc']} | {r['run']} | ERROR: {r['error'][:120]} |")
            continue
        cells = [f"{r['fields'][f]['confidence']:.2f}{'' if r['fields'][f]['correct'] else ' ✗'}" for f in FIELDS]
        lines.append(f"| {r['doc']} | {r['run']} | " + " | ".join(cells) + f" | {r['seconds']:.1f} |")
    return "\n".join(lines)


def wrong_values(data: dict) -> str:
    from evals.harness import DOCS
    counts: dict[tuple, int] = {}
    for r in data["results"]:
        for f, v in r.get("fields", {}).items():
            if not v["correct"]:
                key = (r["doc"], f, DOCS[r["doc"]][f], v["value"])
                counts[key] = counts.get(key, 0) + 1
    if not counts:
        return "None."
    lines = ["| Doc | Field | Expected | Got | Times |", "|---|---|---|---|---|"]
    lines += [f"| {d} | {f} | `{e}` | `{g}` | {n} |" for (d, f, e, g), n in sorted(counts.items())]
    return "\n".join(lines)


def scorecard(data: dict) -> dict:
    ok = [r for r in data["results"] if "error" not in r]
    card = {"model": data["deployment"], "reads": len(ok), "errors": len(data["results"]) - len(ok)}
    if not ok:
        return card
    cells = [r["fields"][f] for r in ok for f in FIELDS]
    right = [c["confidence"] for c in cells if c["correct"]]
    wrong = [c["confidence"] for c in cells if not c["correct"]]
    crit = [r["fields"][f]["correct"] for r in ok for f in ("routing_number_aba", "account_number")]
    # Two-pass simulation: pair consecutive reads of a doc. A wrong value is "silent" when the
    # second read agrees with it and (for ABA) it also passes the checksum, so nothing flags it.
    silent = pairs = 0
    by_doc: dict[str, list] = {}
    for r in ok:
        by_doc.setdefault(r["doc"], []).append(r)
    for rs in by_doc.values():
        for a, b in zip(rs[::2], rs[1::2]):
            pairs += 1
            for f in FIELDS:
                va = a["fields"][f]["value"]
                if a["fields"][f]["correct"] or norm(va) != norm(b["fields"][f]["value"]):
                    continue
                if f == "routing_number_aba" and not is_valid_aba((va or "").replace("-", "").replace(" ", "")):
                    continue
                silent += 1
    card.update({
        "field accuracy": f"{len(right)}/{len(cells)} ({len(right) / len(cells):.0%})",
        "ABA+account accuracy": f"{sum(crit)}/{len(crit)} ({sum(crit) / len(crit):.0%})",
        "docs fully right": f"{sum(all(r['fields'][f]['correct'] for f in FIELDS) for r in ok)}/{len(ok)}",
        "mean conf (right)": f"{st.mean(right):.2f}" if right else "-",
        "mean conf (wrong)": f"{st.mean(wrong):.2f}" if wrong else "-",
        "silent errors (2-pass)": f"{silent} in {pairs} pairs",
        "median s": f"{st.median(r['seconds'] for r in ok):.1f}",
        "tokens in/out": f"{st.mean(r['input_tokens'] or 0 for r in ok):.0f}/{st.mean(r['output_tokens'] or 0 for r in ok):.0f}",
    })
    return card


def card_table(cards: list[dict]) -> str:
    keys = list(max(cards, key=len))
    lines = ["| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    lines += ["| " + " | ".join(str(c.get(k, "-")) for k in keys) + " |" for c in cards]
    return "\n".join(lines)


def main() -> None:
    cards = []
    for path in sorted(EVALS.glob("*/results.json")):
        data = json.loads(path.read_text())
        card = scorecard(data)
        cards.append(card)
        (path.parent / "report.md").write_text(
            f"# {data['deployment']}\n\n{data['reads']} reads per document. ✗ = wrong value.\n\n"
            f"## Scorecard\n\n{card_table([card])}\n\n"
            f"## Confidence per run\n\n{runs_table(data)}\n\n"
            f"## Wrong values\n\n{wrong_values(data)}\n"
        )
    (EVALS / "SCORECARD.md").write_text("# Model scorecard\n\nGenerated by `python -m evals.report`.\n\n" + card_table(cards) + "\n")
    print(card_table(cards))


if __name__ == "__main__":
    main()
